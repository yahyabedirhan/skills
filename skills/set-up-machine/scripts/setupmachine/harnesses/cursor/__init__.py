"""Cursor's local environments, the desktop app and the `cursor-agent` CLI, share `~/.cursor/`:
its hook payload, and the checks both environments run (references/cursor/index.md). Each
environment is a module here: cli.py, desktop.py and cloud.py.

Cursor can't follow a link to the shared file, so `~/.cursor/rules/global-instructions.mdc` is a
generated copy of it. Its CLI also reads Claude Code's permission lists and imports Claude Code's
plugins, so some checks read Claude Code's files through the claude_code package.
"""
from __future__ import annotations

import json
import re
from dataclasses import replace
from pathlib import Path

from .. import claude_code
from ...checks import (Cell, any_wired_problem, as_list, cell, dig, generated_problem, harness_instructions_problem, na,
                       personal_problems, read_json, skill_problems)
from ...hook import ToolCall, refusal, search_pair

# The harness id: the key in setup/harnesses.json and installs.json, and the hook's --harness.
HARNESS = "cursor"
FOLDER = Path(".cursor")
COPY_MARK = ("<!-- Generated by set-up-machine from the shared global instructions file, ~/.config/agents/AGENTS.md. "
             "Edit that file and run `/set-up-machine`; changes here are overwritten. -->")
FRONT = "---\nalwaysApply: true\n---\n"
EVENTS = ("beforeShellExecution", "beforeMCPExecution", "beforeReadFile", "preToolUse")
FILE_TOOLS = {"Read": "read", "Grep": "read", "Write": "write", "Delete": "write"}


# --- the hook ------------------------------------------------------------------------------


def read(payload: dict) -> ToolCall:
    """One of Cursor's four hook events as a tool call. Cursor has no ask list and can run a
    tool without asking, so every call is unattended and every ask row is refused."""
    def text(key, source=payload):
        return source.get(key) if isinstance(source.get(key), str) else ""

    roots = payload.get("workspace_roots")
    root = roots[0] if isinstance(roots, list) and roots and isinstance(roots[0], str) else ""
    call = ToolCall(tool="", cwd=text("cwd") or root,
                    session=text("conversation_id") or text("session_id"),
                    unattended="Cursor, which can run tools without asking", no_native_ask=True)
    event = text("hook_event_name")
    if event == "beforeShellExecution":
        return replace(call, tool="Shell", command=text("command") or None)
    if event == "beforeMCPExecution":
        server, tool = text("mcp_server_name"), text("tool_name")
        return replace(call, tool=f"mcp__{server}__{tool}" if server and tool else tool)
    if event == "beforeReadFile":
        return replace(call, tool="Read", files=((text("file_path"), "read"),) if text("file_path") else ())
    tool, args = text("tool_name"), payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
    path = text("file_path", args) or text("path", args)
    return replace(call, tool=tool, command=text("command", args) or None if tool == "Shell" else None,
                   files=((path, FILE_TOOLS[tool]),) if tool in FILE_TOOLS and path else (),
                   searches=search_pair(args, "path", "glob") if tool == "Grep" else ())


def write(denials: list, asks=()) -> str:
    """Always JSON: a deny, or `{}`, which leaves the call to Cursor's own permissions."""
    if not denials:
        return "{}\n"
    reason = refusal(denials)
    return json.dumps({"permission": "deny", "user_message": reason, "agent_message": reason}) + "\n"


# --- the checks both local environments run ---------------------------------------------


def check_instructions(ctx) -> Cell:
    """The rule file copies the shared file, and Cursor's own instructions match their source."""
    rules = ctx.home / FOLDER / "rules"
    shared = ctx.shared.read_text() if ctx.shared.is_file() else ""
    problems = [generated_problem(ctx, rules / "global-instructions.mdc", f"{FRONT}{COPY_MARK}\n\n{shared}")]
    problems.append(harness_instructions_problem(ctx, HARNESS, rules / "harness-instructions.mdc", FRONT))
    return cell([p for p in problems if p])


def check_guardrails(ctx, cli_lists: bool = True) -> Cell:
    """Each of the four events runs the hook; personal permissions are in the CLI's lists or Claude Code's.
    The desktop app reads no allow or deny list, so it passes cli_lists=False and checks only the hook."""
    path = ctx.home / FOLDER / "hooks.json"
    hooks = dig(read_json(path) or {}, "hooks")
    hooks = hooks if isinstance(hooks, dict) else {}
    problems = []
    for event in EVENTS:
        commands = [h.get("command") for h in as_list(hooks.get(event)) if isinstance(h, dict)]
        problem = any_wired_problem(ctx, path, commands, HARNESS)
        if problem:
            problems.append((problem[0], f"{event}: {problem[1]}"))
    if not cli_lists:
        return cell(problems)
    config = ctx.home / FOLDER / "cli-config.json"
    lists = claude_code.native_lists(read_json(ctx.home / ".claude/settings.json") or {})
    for name, entries in _cli_lists(read_json(config) or {}).items():
        lists[name] += entries
    del lists["ask"]  # Cursor has no ask list: the hook refuses ask rows
    return cell(problems + personal_problems(ctx, lists, config))


def check_plugins(ctx) -> Cell:
    """A bundle comes from Claude Code, installed and enabled there; an MCP server is in ~/.cursor/mcp.json."""
    entries = ctx.setup.plugins(HARNESS)
    if not entries:
        return na("installs.json lists no plugin for Cursor")
    from_claude = claude_code.plugins_installed(ctx.home)
    servers = dig(read_json(ctx.home / FOLDER / "mcp.json") or {}, "mcpServers") or {}
    problems = []
    for entry in entries:
        if entry["kind"] == "bundle" and not from_claude.get(entry["source"]):
            problems.append(("FAIL", f"{entry['source']} needs installing and enabling in Claude Code, "
                                     "which Cursor imports bundles from"))
        elif entry["kind"] == "mcp" and servers.get(entry["name"]) != entry["server"]:
            problems.append(("FAIL", f"{entry['name']} is missing or differs in ~/.cursor/mcp.json"))
    return cell(problems)


def check_skills(ctx) -> Cell:
    return cell(skill_problems(ctx, [ctx.home / ".agents/skills", ctx.home / FOLDER / "skills"]))


def _cli_lists(config: dict) -> dict:
    """cli-config.json's deny and allow lists, as (kind, text) entries."""
    lists = {}
    for name in ("deny", "allow"):
        entries = []
        for entry in dig(config, "permissions", name) or []:
            match = re.fullmatch(r"(Shell|Read|Write|Mcp)\((.+)\)", entry) if isinstance(entry, str) else None
            if not match:
                continue
            tool, inner = match.groups()
            if tool == "Shell":
                entries.append(("command", inner.rstrip(":")))
            elif tool == "Mcp":
                entries.append(("mcp", "mcp__{}__{}".format(*inner.partition(":")[::2])))
            else:
                entries.append(("path", inner))
        lists[name] = entries
    return lists
