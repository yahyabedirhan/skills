"""Cursor's harness setup. It audits Cursor, translates one hook payload, and adapts one plugin entry.

A later harness copies these operations: `id`, `label`, `present`, `audit`, `read`, `write`,
and, when that harness takes plugins, `validate`, `check`, and `propose`. `audit` returns
`(channel, status, text)` for the hook wiring, the run mode, and the generated instructions.
The printed words stay `hook`, `cursor`, and `harness`.
"""
from __future__ import annotations

import copy
import json
from dataclasses import replace
from pathlib import Path

from .. import layout, personal
from ..harnesses import claude, policy
from ..hook import ToolCall, _search, command_script, refusal

id = "cursor"
label = "Cursor"
HOME_DIR = Path(".cursor")
RULE = Path(".cursor/rules/harness-instructions.mdc")
MARK = "<!-- Generated by set-up-machine from the workstation repo's "
EVENTS = ("beforeShellExecution", "beforeMCPExecution", "beforeReadFile", "preToolUse")
FILE_TOOLS = {"Read": "read", "Grep": "read", "Write": "write", "Delete": "write"}
UNATTENDED = "Cursor, which can run tools without asking"


def present(home: Path) -> bool:
    """Whether Cursor is set up on this machine: `~/.cursor` exists."""
    return (home / HOME_DIR).is_dir()


def audit(home: Path) -> list:
    """`(channel, status, text)` for Cursor's wiring, run mode, and generated instructions."""
    lines = [("hook", *_wiring(home))]
    lines.extend(_run_mode(home))
    lines.extend(("harness", status, text) for status, text in instructions(home))
    return lines


def instructions(home: Path) -> list:
    """`(status, text)` for Cursor's generated instructions. None when there is nothing to say.

    A malformed harnesses file is the shared reader's line, so this returns nothing for it.
    """
    try:
        pointer = personal.read_pointer(home)
    except personal.PersonalError:
        return []
    if not pointer.repository:
        return []
    try:
        layout.harness_files(pointer.clone)
    except layout.LayoutError:
        return []
    target = home / RULE
    written = target.read_text() if target.is_file() else None
    ours = written is not None and MARK in written
    if written is not None and not ours:
        return [("gap", f"{label}: {target} wasn't written by set-up-machine; left alone")]
    try:
        source = layout.harness_file(pointer.clone, id, "instructions")
    except layout.LayoutError as exc:
        return [("FAIL", f"{label}: {exc}")]
    if source is None:
        if ours:
            return [("FAIL", f"{label}: {target} was generated, but {pointer.clone / layout.HARNESSES} "
                              f"points at no instructions for {id}; remove it")]
        return []
    if not present(home):
        return [("n/a", f"{label}: not set up here, so {source} isn't written")]
    try:
        want = harness_rule(source.read_text(), source.relative_to(pointer.clone).as_posix())
    except personal.PersonalError as exc:
        return [("FAIL", f"{source} {exc}")]
    if written is None:
        return [("FAIL", f"{label}: {target} doesn't exist; set-up-machine writes it from {source}")]
    if written != want:
        return [("FAIL", f"{label}: {target} differs from {source}")]
    return [("ok", f"{label}: {target} matches {source}")]


def harness_rule(source: str, path: str) -> str:
    """The text set-up-machine writes for Cursor, from its source file's `## Instructions` section.

    path is the source's path relative to the workstation repo's root, as its header names it.
    """
    section = personal._section(source, personal.HARNESS_SECTION)
    if not section:
        raise personal.PersonalError(f"has no `{personal.HARNESS_SECTION}` section")
    return (f"---\nalwaysApply: true\n---\n{MARK}{path}. Edit that file and run `/set-up-machine`; "
            f"changes here are overwritten. -->\n\n{section}\n")


def read(payload: dict) -> ToolCall:
    """Cursor's hook payload as one tool call. Cursor refuses every ask row: it has no ask list."""
    return replace(_read(payload), unattended=UNATTENDED, no_native_ask=True)


def write(denials: list, asks=()) -> str:
    """Cursor's JSON answer: a deny, or `{}`, which leaves the call to its own permissions.

    The CLI shows the agent `user_message`. `agent_message` carries the same text.
    """
    if not denials:
        return "{}\n"
    reason = refusal(denials)
    return json.dumps({"permission": "deny", "user_message": reason, "agent_message": reason}) + "\n"


def validate(entry: dict, where: str):
    policy.validate(entry, where)


def server_name(source: str, server: str) -> str:
    """The name Cursor gives an MCP server of a Claude Code plugin it imports."""
    return f"plugin-{source.split('@', 1)[0]}-{server}"


def check(ctx, tag: str, entry: dict) -> list:
    home = ctx.home
    folder = home / HOME_DIR
    if not folder.is_dir():
        return [("n/a", f"Cursor: {tag} isn't checked; Cursor is not set up here")]
    if entry["kind"] == "bundle":
        source = entry["source"]
        if not ctx.claude_plugins.get(source):
            return [("FAIL", f"Cursor: {tag} needs {source} installed and enabled in Claude Code, since Cursor "
                             "imports bundles only from Claude Code")]
        names = [server_name(source, s) for s in claude.bundle_servers(home, source)]
        how = f"as {', '.join(names)}" if names else "(skills only; no MCP server)"
        lines = [("ok", f"Cursor: {tag} is imported from Claude Code {how}; declaration matches, readiness only; latest release is unverified")]
        lines.extend(_tool_lines(home, tag, entry, policy.effective(entry, ctx.rules)))
        return lines
    path = folder / "mcp.json"
    try:
        servers = json.loads(path.read_text()).get("mcpServers", {}) if path.is_file() else {}
    except (OSError, ValueError, AttributeError):
        return [("FAIL", f"Cursor: {tag} can't be checked; {path} isn't valid JSON")]
    if not isinstance(servers, dict) or entry["name"] not in servers:
        return [("FAIL", f"Cursor: {tag} has no entry in {path}")]
    if servers[entry["name"]] != entry["server"]:
        return [("FAIL", f"Cursor: {tag} entry in {path} differs from installs.json")]
    return [("ok", f"Cursor: {tag} is in {path}")]


def propose(document: dict, entry: dict, rules=()) -> dict:
    """mcp.json with this standalone server merged. A bundle has nothing to write here."""
    validate(entry, "plugin")
    if entry["kind"] != "mcp":
        return copy.deepcopy(document or {})
    result = copy.deepcopy(document or {})
    servers = result.setdefault("mcpServers", {})
    if not isinstance(servers, dict):
        servers = {}
        result["mcpServers"] = servers
    servers[entry["name"]] = dict(entry["server"])
    return result


def _wiring(home: Path):
    folder = home / HOME_DIR
    if not folder.is_dir():
        return ("none", f"{label}: not set up here (no ~/{HOME_DIR})")
    path = folder / "hooks.json"
    hooks = (_json(path) or {}).get("hooks")
    hooks = hooks if isinstance(hooks, dict) else {}
    missing, scripts = [], set()
    for event in EVENTS:
        found = [command_script(h["command"], id, home) for h in hooks.get(event) or []
                 if isinstance(h, dict) and isinstance(h.get("command"), str)]
        found = [s for s in found if s]
        if found:
            scripts.add(found[0])
        else:
            missing.append(event)
    if missing:
        return ("FAIL", f"{label}: {path} has no pre-tool hook on {', '.join(missing)}")
    gone = [s for s in scripts if not s.is_file()]
    if gone:
        return ("FAIL", f"{label}: {path} runs {gone[0]}, which doesn't exist")
    return ("wired", f"{label}: {path} -> {', '.join(str(s) for s in sorted(scripts))} on all four events")


def _run_mode(home: Path) -> list:
    """`(channel, status, text)` for Cursor's run mode: auto-review, with the sandbox enabled.

    `none` when Cursor isn't set up. `ok` when both keys are set. `FAIL` when
    `~/.cursor` exists and either key is missing or different. Other keys are kept.
    """
    folder = home / HOME_DIR
    if not folder.is_dir():
        return [("cursor", "none", f"{label}: not set up here (no ~/{HOME_DIR})")]
    path = folder / "cli-config.json"
    data = _json(path) or {}
    sandbox = data.get("sandbox")
    sandbox_mode = sandbox.get("mode") if isinstance(sandbox, dict) else None
    missing = []
    if data.get("approvalMode") != "auto-review":
        missing.append("approvalMode auto-review")
    if sandbox_mode != "enabled":
        missing.append("sandbox.mode enabled")
    if missing:
        return [("cursor", "FAIL", f"{label}: {path} lacks {', '.join(missing)}")]
    return [("cursor", "ok", f"{label}: {path} has approvalMode auto-review and sandbox.mode enabled")]


def _read(payload: dict) -> ToolCall:
    def text(key, source=payload):
        value = source.get(key)
        return value if isinstance(value, str) else ""

    event = text("hook_event_name")
    roots = payload.get("workspace_roots")
    cwd = text("cwd") or (roots[0] if isinstance(roots, list) and roots and isinstance(roots[0], str) else "")
    session = text("conversation_id") or text("session_id")
    if event == "beforeShellExecution":
        return ToolCall(tool="Shell", command=text("command") or None, cwd=cwd, session=session)
    if event == "beforeMCPExecution":
        server, tool = text("mcp_server_name"), text("tool_name")
        return ToolCall(tool=f"mcp__{server}__{tool}" if server and tool else tool, cwd=cwd, session=session)
    if event == "beforeReadFile":
        path = text("file_path")
        return ToolCall(tool="Read", files=((path, "read"),) if path else (), cwd=cwd, session=session)
    tool = text("tool_name")
    tool_input = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
    files = ()
    if tool in FILE_TOOLS:
        path = text("file_path", tool_input) or text("path", tool_input)
        files = ((path, FILE_TOOLS[tool]),) if path else ()
    command = text("command", tool_input) if tool == "Shell" else ""
    searches = _search(tool_input, "path", "glob") if tool == "Grep" else ()
    return ToolCall(tool=tool, command=command or None, files=files, cwd=cwd, session=session, searches=searches)


def _json(path: Path):
    try:
        data = json.loads(path.read_text())
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def _tool_lines(home, tag, entry, chosen) -> list:
    """Cursor imports Claude Code's deny list, so the derived tools are checked there."""
    disabled = chosen.get("disabled_tools") or []
    if not disabled:
        return []
    path = home / ".claude/settings.json"
    try:
        permissions = json.loads(path.read_text()).get("permissions", {})
    except (OSError, ValueError, AttributeError):
        permissions = {}
    deny = permissions.get("deny") if isinstance(permissions, dict) else None
    deny = deny if isinstance(deny, list) else []
    missing = [tool for tool in disabled if not claude.denied(deny, entry["name"], tool)]
    if missing:
        return [("FAIL", f"Cursor: {tag} denies {', '.join(missing)} from the derived tool list; "
                         "Cursor imports Claude Code's deny list, which lacks them")]
    return [("ok", f"Cursor: {tag} tool list matches the derived tool list through Claude Code's deny list")]
