"""Codex adapter: global instructions by symlink, the table as Starlark prefix rules, the
pre-tool hook in hooks.json, and memory off in config.toml.

Facts it relies on (see references/codex.md and docs/research/harness-capabilities.md, section 2):
- `~/.codex/AGENTS.md` loads in every session and may be a symlink; it has no imports.
  A non-empty `~/.codex/AGENTS.override.md` is read instead of it.
- Every `~/.codex/rules/*.rules` file loads; `prefix_rule(pattern, decision, justification)`
  matches an argv prefix token by token, an element being one word or a list of
  alternatives. The strictest matching decision wins across files. A `forbidden`
  rule's justification is what the agent reads when it's refused. Codex resolves an
  absolute program path to its basename, so `/bin/rm` needs no rule of its own.
- Codex runs every shell command as `[<shell>, "-lc", <command>]` (`-c` when login is
  off), and matches a rule against that argv when the command isn't a plain chain
  of words, so a rule on `bash -c` or `zsh -lc` would refuse its own wrapper.
- `~/.codex/hooks.json` holds `hooks.PreToolUse` matcher groups like Claude Code's. A
  non-managed hook runs only once trusted: `[hooks.state."<file>:pre_tool_use:<group>:<handler>"]
  trusted_hash` in config.toml, a sha256 of the hook's normalised identity.
- `[features] memories = false` in config.toml keeps local memories off; they're
  written under `~/.codex/memories/`. A trusted project's `.codex/config.toml` can
  turn memories on or hooks off; only a system `requirements.toml` pins them.
"""
